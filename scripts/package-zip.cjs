'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const assert=require('node:assert/strict');
const {zipSync,unzipSync}=require('fflate');
const {root}=require('./public-files.cjs');
require('./verify-release.cjs');
const manifest=require('../manifest.json');
const files=['main.js','manifest.json','styles.css'];
const output=path.join(root,'dist','keep-view');
const entries=Object.fromEntries(files.map(name=>['keep-view/'+name,[fs.readFileSync(path.join(output,name)),{mtime:new Date(1980,0,1)}]]));
const zip=zipSync(entries,{level:9});
const unpacked=unzipSync(zip);
assert.deepEqual(Object.keys(unpacked).sort(),files.map(name=>'keep-view/'+name).sort());
for(const name of files) assert.deepEqual(Buffer.from(unpacked['keep-view/'+name]),fs.readFileSync(path.join(output,name)));
const directory=path.join(root,'.artifacts','releases');fs.mkdirSync(directory,{recursive:true});
const filename=`keep-view-${manifest.version}-community-candidate.zip`;
fs.writeFileSync(path.join(directory,filename),zip);
const checksums=files.map(name=>crypto.createHash('sha256').update(fs.readFileSync(path.join(output,name))).digest('hex')+'  '+name);
checksums.push(crypto.createHash('sha256').update(zip).digest('hex')+'  '+filename);
fs.writeFileSync(path.join(directory,`keep-view-${manifest.version}-SHA256SUMS.txt`),checksums.join('\n')+'\n');
console.log('Candidate ZIP and SHA256 checksums verified in .artifacts/releases/.');
